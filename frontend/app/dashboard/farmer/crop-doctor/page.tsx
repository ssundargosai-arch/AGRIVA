"use client";

import Link from "next/link";
import { ChangeEvent, useState } from "react";
import {
  ArrowLeft,
  Camera,
  Loader2,
  Upload,
} from "lucide-react";

const API_URL =
  process.env.NEXT_PUBLIC_API_URL ||
  "http://127.0.0.1:8000";

type DiseaseResult = {
  crop: string;
  possible_disease: string;
  confidence: number;
  severity: string;
  recommendations: string[];
  demo_prediction: boolean;
  model_note: string;
};

export default function CropDoctorPage() {
  const [file, setFile] =
    useState<File | null>(null);

  const [result, setResult] =
    useState<DiseaseResult | null>(null);

  const [loading, setLoading] =
    useState(false);

  const [error, setError] =
    useState("");

  function selectFile(
    event: ChangeEvent<HTMLInputElement>
  ) {
    const selectedFile =
      event.target.files?.[0] || null;

    setFile(selectedFile);
    setResult(null);
    setError("");
  }

  async function analyzeCrop() {
    if (!file) {
      setError(
        "Please select or capture a crop image."
      );
      return;
    }

    const token =
      localStorage.getItem("access_token");

    if (!token) {
      setError("Please login first.");
      return;
    }

    const formData = new FormData();

    formData.append(
      "file",
      file
    );

    setLoading(true);
    setError("");

    try {
      const response = await fetch(
        `${API_URL}/api/ai/crop-disease`,
        {
          method: "POST",
          headers: {
            Authorization: `Bearer ${token}`,
          },
          body: formData,
        }
      );

      const data = await response.json();

      if (!response.ok) {
        throw new Error(
          data.detail ||
            "Crop analysis failed"
        );
      }

      setResult(data);
    } catch (err) {
      setError(
        err instanceof Error
          ? err.message
          : "Crop analysis failed"
      );
    } finally {
      setLoading(false);
    }
  }

  return (
    <main className="min-h-screen bg-slate-50">
      <div className="mx-auto max-w-5xl px-6 py-8">
        <Link
          href="/dashboard/farmer"
          className="inline-flex items-center gap-2 text-green-700"
        >
          <ArrowLeft size={18} />
          Farmer Dashboard
        </Link>

        <div className="mt-8">
          <h1 className="text-3xl font-bold text-slate-900">
            AGRIVA Crop Doctor
          </h1>

          <p className="mt-2 text-slate-600">
            Upload or capture a crop image
            for CropSense analysis.
          </p>
        </div>

        <section className="mt-8 rounded-2xl border bg-white p-6 shadow-sm">
          <label className="flex cursor-pointer flex-col items-center rounded-xl border-2 border-dashed border-green-200 bg-green-50/40 p-10">
            <Camera
              size={44}
              className="text-green-700"
            />

            <span className="mt-4 font-semibold text-slate-800">
              Select or capture crop image
            </span>

            <span className="mt-1 text-sm text-slate-500">
              JPG, JPEG or PNG
            </span>

            <input
              type="file"
              accept="image/*"
              capture="environment"
              onChange={selectFile}
              className="hidden"
            />
          </label>

          {file && (
            <div className="mt-4 rounded-lg bg-slate-50 p-3 text-sm text-slate-700">
              Selected: {file.name}
            </div>
          )}

          <button
            type="button"
            onClick={analyzeCrop}
            disabled={loading}
            className="mt-5 flex w-full items-center justify-center gap-2 rounded-xl bg-green-700 py-3 font-semibold text-white hover:bg-green-800 disabled:bg-slate-400"
          >
            {loading ? (
              <Loader2 className="animate-spin" />
            ) : (
              <Upload />
            )}

            {loading
              ? "Analyzing Crop..."
              : "Analyze Crop"}
          </button>

          {error && (
            <div className="mt-5 rounded-lg bg-red-50 p-3 text-red-700">
              {error}
            </div>
          )}
        </section>

        {result && (
          <section className="mt-8 rounded-2xl border bg-white p-6 shadow-sm">
            {result.demo_prediction && (
              <div className="mb-6 rounded-xl border border-amber-200 bg-amber-50 p-4 text-amber-800">
                <strong>
                  DEMO PREDICTION
                </strong>

                <p className="mt-1 text-sm">
                  This result is generated by
                  AGRIVA demo logic and is not
                  produced by a trained disease
                  detection model.
                </p>
              </div>
            )}

            <h2 className="text-2xl font-bold text-slate-900">
              {result.possible_disease}
            </h2>

            <div className="mt-6 grid gap-4 sm:grid-cols-3">
              <div className="rounded-xl bg-green-50 p-4">
                <p className="text-sm text-slate-500">
                  Crop
                </p>

                <p className="mt-1 text-lg font-bold">
                  {result.crop}
                </p>
              </div>

              <div className="rounded-xl bg-blue-50 p-4">
                <p className="text-sm text-slate-500">
                  Confidence
                </p>

                <p className="mt-1 text-lg font-bold">
                  {result.confidence}%
                </p>
              </div>

              <div className="rounded-xl bg-amber-50 p-4">
                <p className="text-sm text-slate-500">
                  Severity
                </p>

                <p className="mt-1 text-lg font-bold">
                  {result.severity}
                </p>
              </div>
            </div>

            <h3 className="mt-7 text-lg font-bold">
              Recommendations
            </h3>

            <ul className="mt-3 list-disc space-y-2 pl-5 text-slate-700">
              {result.recommendations.map(
                (recommendation) => (
                  <li key={recommendation}>
                    {recommendation}
                  </li>
                )
              )}
            </ul>

            <p className="mt-6 text-xs text-slate-500">
              {result.model_note}
            </p>
          </section>
        )}
      </div>
    </main>
  );
}